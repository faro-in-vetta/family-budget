--  Family Budget — міграція 004: скільки відкладаємо на подушку щомісяця
--
--  Поле потрібне, щоб рахувати «Потрібно заробляти»: витрати + цілі +
--  подушка. Без нього подушка росла лише з того, що випадково лишилось.
--
--  Запускати в Supabase → SQL Editor → New query → Run. Безпечно повторювати.
-- ═══════════════════════════════════════════════════════════════════

alter table settings
  add column if not exists cushion_monthly numeric not null default 0
  check (cushion_monthly >= 0);

comment on column settings.cushion_monthly is
  'Скільки родина планує відкладати на подушку щомісяця, у євро.';
